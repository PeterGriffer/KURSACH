const url="http://localhost:8080/track";

function sendAnalytics(eventData) {
    // 1. Логируем в консоль
    console.log('Analytics:', eventData);
    // 2. Пытаемся отправить на бэкенд

     fetch(url, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json'
        },
        body: JSON.stringify(eventData)
    }).catch(error => {
        console.log('Бэкенд недоступен, но это нормально пока');
    });

}
const textElement=document.querySelector('.text');

function getRandomIndex(mass){
    const randomIndex=Math.floor(Math.random()*mass.length);
    return randomIndex;
}

function onClickButton1 (){
    var message=motivatingPhrases[getRandomIndex(motivatingPhrases)];
    textElement.textContent=message;
    const message_to_serverr={
        event: "click",
        button: 1,
        message: message, 
        timestamp: new Date().toISOString()
    }
    sendAnalytics(message_to_serverr);
    umami.track('Кнопка 1', {
        button: 1,
        category: 'мотивация',
        message: message
    });
}
